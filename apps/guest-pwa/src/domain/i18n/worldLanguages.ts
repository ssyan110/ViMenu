export function formatLanguageLabel(codeRaw: string) {
  const code = codeRaw.toLowerCase();
  const baseCode = code.split(/[-_]/)[0] ?? code;
  const meta = WORLD_LANGUAGES[baseCode];

  let englishFromIntl: string | undefined;
  let viFromIntl: string | undefined;
  if (!meta) {
    try {
      englishFromIntl = new Intl.DisplayNames(["en"], { type: "language" }).of(
        baseCode,
      );
      viFromIntl = new Intl.DisplayNames(["vi"], { type: "language" }).of(
        baseCode,
      );
    } catch {
      // ignore
    }
  }

  return {
    code,
    primary:
      meta?.nativeName ??
      meta?.englishName ??
      englishFromIntl ??
      baseCode.toUpperCase(),
    secondary:
      meta?.viName ??
      viFromIntl ??
      meta?.englishName ??
      englishFromIntl ??
      baseCode.toUpperCase(),
  };
}
